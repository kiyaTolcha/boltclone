/**
 * ingestion.js - Session Ingestion Normalizer
 *
 * Merges split Chrome webRequest lifecycle events into unified TransactionDTOs,
 * decodes body envelopes, sanitizes transport headers, and enforces target host
 * scope boundaries.
 *
 * Each Chrome webRequest transaction is split across three events fired by the
 * extension into `boltcloneTraffic`:
 *   - onBeforeRequest  → { id, url, method, requestBody }
 *   - onSendHeaders    → { id, requestHeaders }
 *   - onHeadersReceived→ { id, statusCode, responseHeaders }
 *
 * This module ports groupById() from chrome-extension/rules.js into the CLI
 * and extends it with full normalization for authenticated replay and scanning.
 */

'use strict';

// Transport / browser headers that must never be forwarded in fetch() replay.
// These are controlled by the browser/OS and would corrupt the request or
// cause the scanner to impersonate the wrong host.
const NOISE_HEADERS = new Set([
  'host',
  'content-length',
  'connection',
  'transfer-encoding',
  'upgrade-insecure-requests',
  'te',
  'trailer',
  'proxy-authorization',
  'proxy-connection',
  // Chrome client-hint headers
  'sec-ch-ua',
  'sec-ch-ua-mobile',
  'sec-ch-ua-platform',
  'sec-ch-ua-platform-version',
  'sec-ch-ua-arch',
  'sec-ch-ua-bitness',
  'sec-ch-ua-full-version',
  'sec-ch-ua-full-version-list',
  'sec-ch-ua-model',
  'sec-ch-ua-wow64',
  // Fetch metadata headers (regenerated by browser, not by CLI)
  'sec-fetch-dest',
  'sec-fetch-mode',
  'sec-fetch-site',
  'sec-fetch-user',
]);

/**
 * Groups raw Chrome webRequest log entries by their shared `id` field,
 * merging properties from all three lifecycle events into one object.
 *
 * Ported from chrome-extension/rules.js:groupById().
 *
 * @param {Array<object>} logEntries  Raw event objects from boltcloneTraffic.
 * @returns {Array<object>}           One merged object per unique request id.
 */
export function groupById(logEntries) {
  const byId = new Map();
  for (const entry of logEntries) {
    if (!entry.id) continue;
    const existing = byId.get(entry.id) || {};
    // Later events overlay earlier ones. Array fields (headers) from
    // onSendHeaders / onHeadersReceived replace undefined slots; they do not
    // need to be merged since each event owns distinct field names.
    byId.set(entry.id, { ...existing, ...entry });
  }
  return Array.from(byId.values());
}

/**
 * Decodes the Chrome extension requestBody envelope into a plain JS object
 * suitable for mutation and serialization.
 *
 * Chrome normalizes request bodies into one of two envelope shapes:
 *   1. JSON payloads: { raw: [{ text: '{"key":"val"}' }] }
 *   2. Form payloads: { formData: { key: ['value'] } }
 *
 * @param {object|null} requestBody  The `requestBody` field from a merged entry.
 * @param {string} [contentType=''] The request Content-Type header value.
 * @returns {{ decoded: object|string|null, format: 'json'|'form'|'raw'|'empty' }}
 */
export function decodeRequestBody(requestBody, contentType = '') {
  if (!requestBody) return { decoded: null, format: 'empty' };

  // Chrome raw body envelope: used for JSON and other non-form bodies.
  if (Array.isArray(requestBody.raw) && requestBody.raw.length > 0) {
    const text = requestBody.raw.map((chunk) => chunk.text ?? '').join('');
    // Attempt JSON parse if the content type hints at it or if the text starts
    // with a JSON structural character.
    const lct = contentType.toLowerCase();
    if (lct.includes('application/json') || lct.includes('+json') || /^\s*[\[{]/.test(text)) {
      try {
        return { decoded: JSON.parse(text), format: 'json' };
      } catch {
        // Not valid JSON despite hints; treat as raw string.
      }
    }
    return { decoded: text, format: 'raw' };
  }

  // Chrome formData envelope: { key: [value1, value2] }
  if (requestBody.formData && typeof requestBody.formData === 'object') {
    // Flatten single-value arrays to scalar strings for easier mutation.
    const flat = {};
    for (const [key, values] of Object.entries(requestBody.formData)) {
      flat[key] = Array.isArray(values) && values.length === 1 ? values[0] : values;
    }
    return { decoded: flat, format: 'form' };
  }

  return { decoded: null, format: 'empty' };
}

/**
 * Converts a Chrome `[{ name, value }]` header array into a lowercased
 * `Record<string, string>` map, dropping noise/transport headers.
 *
 * @param {Array<{name: string, value: string}>} headersArray
 * @returns {Record<string, string>}
 */
export function sanitizeHeaders(headersArray) {
  if (!Array.isArray(headersArray)) return {};
  const result = {};
  for (const { name, value } of headersArray) {
    if (!name) continue;
    const lower = name.toLowerCase();
    if (NOISE_HEADERS.has(lower)) continue;
    // Keep the last value seen for a given header name (matches fetch behavior).
    result[lower] = value ?? '';
  }
  return result;
}

/**
 * Normalizes a raw session export from the Chrome extension into an array of
 * canonical TransactionDTO objects scoped to a single target hostname.
 *
 * Supported input envelopes:
 *   1. `{ boltcloneTraffic: [...] }` — primary extension export format.
 *   2. `{ analysis: [...] }`         — legacy analysis-only export.
 *   3. `[...]`                        — raw array (direct boltcloneTraffic contents).
 *
 * TransactionDTO shape:
 * ```
 * {
 *   id:              string,          // Chrome request id
 *   url:             string,          // Full request URL
 *   method:          string,          // HTTP method (uppercase)
 *   statusCode:      number|null,     // Response status, if captured
 *   headers:         Record<string,string>, // Sanitized request headers
 *   responseHeaders: Record<string,string>, // Response headers (lowercased)
 *   body:            object|string|null,    // Decoded request body
 *   bodyFormat:      'json'|'form'|'raw'|'empty',
 *   isEnriched:      boolean,         // false if no headers/body were captured
 * }
 * ```
 *
 * @param {object|Array} rawSessionData  Parsed JSON from the session file.
 * @param {string}       targetBaseUrl   The scan target (e.g. "https://api.example.com").
 * @returns {Array<TransactionDTO>}
 */
export function normalizeSession(rawSessionData, targetBaseUrl) {
  // --- 1. Unwrap the envelope ---
  let entries;
  if (Array.isArray(rawSessionData)) {
    entries = rawSessionData;
  } else if (rawSessionData && Array.isArray(rawSessionData.boltcloneTraffic)) {
    entries = rawSessionData.boltcloneTraffic;
  } else if (rawSessionData && Array.isArray(rawSessionData.analysis)) {
    // Legacy format: analysis objects have url but no headers/body events.
    entries = rawSessionData.analysis;
  } else {
    entries = [];
  }

  // --- 2. Merge split lifecycle events by request id ---
  const merged = groupById(entries);

  // --- 3. Resolve target hostname for scope filtering ---
  let targetHost;
  try {
    targetHost = new URL(targetBaseUrl).hostname;
  } catch {
    // If targetBaseUrl is malformed accept all entries (fail-open on scope).
    targetHost = null;
  }

  // --- 4. Map to canonical TransactionDTOs ---
  const transactions = [];
  for (const entry of merged) {
    // Every valid entry must have a URL.
    if (!entry.url) continue;

    // Scope boundary: drop transactions targeting different origins.
    if (targetHost) {
      let entryHost;
      try { entryHost = new URL(entry.url).hostname; } catch { continue; }
      if (entryHost !== targetHost) continue;
    }

    // Determine if this entry has enriched request data (headers/body).
    const hasHeaders = Array.isArray(entry.requestHeaders) && entry.requestHeaders.length > 0;
    const hasBody = entry.requestBody != null;
    const isEnriched = hasHeaders || hasBody;

    // Decode request headers.
    const headers = sanitizeHeaders(entry.requestHeaders ?? []);

    // Determine content-type for body decoding.
    const contentType = headers['content-type'] ?? '';

    // Decode request body.
    const { decoded: body, format: bodyFormat } = decodeRequestBody(
      entry.requestBody ?? null,
      contentType
    );

    // Decode response headers (already in { name, value } array form).
    const responseHeaders = sanitizeHeaders(entry.responseHeaders ?? []);

    transactions.push({
      id:              String(entry.id ?? ''),
      url:             entry.url,
      method:          (entry.method ?? 'GET').toUpperCase(),
      statusCode:      typeof entry.statusCode === 'number' ? entry.statusCode : null,
      headers,
      responseHeaders,
      body,
      bodyFormat,
      isEnriched,
    });
  }

  return transactions;
}

